#!/usr/bin/env python3
"""HYPE RIOT pipeline Stage 5 — compile the static dataset.

Writes (deterministically, no timestamps):
  public/data/v1/packs/pack_NNN.json  one match of content per pack
  public/data/v1/pitch.json           full template + wildcard pools (Quick Arcade)
  public/data/v1/manifest.json        counts, Daily schedule (stride), file hashes
  packages/riot-engine/src/action-verbs.ts / action-verbs-lz.ts
                                      the pitch verb dictionary (A-K / L-Z)
"""
import datetime
import hashlib
import json
import sys
from pathlib import Path

HERE = Path(__file__).parent
sys.path.insert(0, str(HERE))
from daily import daily_for, pick_stride  # noqa: E402

OUT = HERE / "output"
ROOT = HERE.parent
PUBLIC = ROOT / "public" / "data" / "v1"
ENGINE_SRC = ROOT / "packages" / "riot-engine" / "src"
DATASET_VERSION = "2.0.0"


def dump(path: Path, obj, pretty=False):
    path.parent.mkdir(parents=True, exist_ok=True)
    text = json.dumps(obj, ensure_ascii=False, indent=2 if pretty else None,
                      separators=None if pretty else (",", ":"))
    path.write_text(text + ("\n" if pretty else ""), encoding="utf-8", newline="\n")


def sha12(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()[:12]


def write_verbs(verbs):
    def ts(name, doc, words):
        body = ",\n".join(
            "  " + ",".join(json.dumps(w) for w in words[i:i + 10]) for i in range(0, len(words), 10)
        )
        return (
            f"// AUTO-GENERATED by pipeline/stage5_compile.py from pipeline/corpus/data/verbs.txt.\n"
            f"// Do not edit by hand. {doc}\n"
            f"export const {name}: readonly string[] = [\n{body},\n];\n"
        )
    a_k = [v for v in verbs if v[0] <= "k"]
    l_z = [v for v in verbs if v[0] > "k"]
    (ENGINE_SRC / "action-verbs-lz.ts").write_text(
        ts("VERBS_L_TO_Z", "Pitch action-verb dictionary, L-Z half.", l_z), encoding="utf-8", newline="\n")
    (ENGINE_SRC / "action-verbs.ts").write_text(
        ts("VERBS_A_TO_K", "Pitch action-verb dictionary, A-K half.", a_k)
        + 'import { VERBS_L_TO_Z } from "./action-verbs-lz";\n\n'
        + "/** Every verb (base form). PitchScorer also accepts inflections. */\n"
        + "export const ACTION_VERBS: ReadonlySet<string> = new Set([...VERBS_A_TO_K, ...VERBS_L_TO_Z]);\n"
        + "export const ACTION_VERB_COUNT = ACTION_VERBS.size;\n",
        encoding="utf-8", newline="\n")


def main():
    packs = json.loads((OUT / "packs.json").read_text(encoding="utf-8"))
    pitch = json.loads((OUT / "pitch.json").read_text(encoding="utf-8"))
    verbs = json.loads((OUT / "verbs.json").read_text(encoding="utf-8"))
    corpus = json.loads((OUT / "corpus.json").read_text(encoding="utf-8"))

    packs_dir = PUBLIC / "packs"
    packs_dir.mkdir(parents=True, exist_ok=True)
    for old in packs_dir.glob("pack_*.json"):  # stale packs from a previous build
        old.unlink()
    for pack in packs:
        dump(packs_dir / f"pack_{pack['id']:03d}.json", pack)
    dump(PUBLIC / "pitch.json", pitch)
    write_verbs(verbs)

    files = {"pitch.json": sha12(PUBLIC / "pitch.json")}
    for pack in packs:
        rel = f"packs/pack_{pack['id']:03d}.json"
        files[rel] = sha12(PUBLIC / rel)
    content_hash = hashlib.sha256("".join(files[k] for k in sorted(files)).encode()).hexdigest()[:12]
    stride = pick_stride(len(packs))
    check_dates = [datetime.date(2026, 1, 1), datetime.date(2026, 11, 26), datetime.date(2027, 6, 1)]
    manifest = {
        "version": DATASET_VERSION,
        "contentHash": content_hash,
        "packs": len(packs),
        "dailyStride": stride,
        "dailyOffset": 0,
        "counts": {
            "prompts": len(packs),
            "answers": sum(len(p["round1"]["answers"]) for p in packs),
            "claims": len(corpus["claims"]),
            "clashes": len(corpus["clashes"]),
            "zoom": len(corpus["zoom"]),
            "templates": len(pitch["templates"]),
            "wildcards": len(pitch["wildcards"]),
            "verbs": len(verbs),
        },
        "dailyCheck": {d.isoformat(): daily_for(d, len(packs), stride)["packId"] for d in check_dates},
        "files": files,
    }
    dump(PUBLIC / "manifest.json", manifest, pretty=True)
    print(f"[stage5] wrote {len(packs)} packs, pitch.json, manifest (stride {stride}), "
          f"{len(verbs)} verbs -> riot-engine; content {content_hash}")


if __name__ == "__main__":
    main()
